import {testHierarchyRoundTrips} from './lib/chart-hierarchy-roundtrip-contract.mjs';
import {testHierarchyCollaboration} from './lib/chart-hierarchy-collab-contract.mjs';
import {testHierarchyBoundaries} from './lib/chart-hierarchy-boundaries-contract.mjs';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {bundleBrowser} from './lib/bundle-browser.mjs';
import {countedAssert} from './lib/counted-assert.mjs';
import {unzipSync,strFromU8,strToU8,zipSync} from 'fflate';
import {JSDOM} from 'jsdom';
const {assert,record}=countedAssert('chartHierarchy');
const root=resolve('.'),out=join(root,'out/chart-hierarchy');mkdirSync(out,{recursive:true});
writeFileSync(join(out,'entry.mjs'),`export * as core from '@web-ppt/core';export * as edit from '@web-ppt/edit-core';export * as chart from '@web-ppt/edit-core/chart';export * as generate from '@web-ppt/edit-core/generate';export * as collab from '@web-ppt/collab';export * as design from '@web-ppt/edit-core/chart-design';`);
const modules=process.argv.includes('--dist') ? Object.fromEntries(await Promise.all([['core','@web-ppt/core'],['edit','@web-ppt/edit-core'],['chart','@web-ppt/edit-core/chart'],['generate','@web-ppt/edit-core/generate'],['collab','@web-ppt/collab'],['design','@web-ppt/edit-core/chart-design']].map(async([key,path])=>[key,await import(path)]))) : await bundleBrowser({root,entry:join(out,'entry.mjs'),output:join(out,'contract.mjs'),aliases:[['@web-ppt/collab',join(root,'packages/collab/src/index.ts')],['@web-ppt/core',join(root,'packages/core/src/index.ts')],['@web-ppt/edit-core',join(root,'packages/edit-core/src/index.ts')]]});
const {core,edit,chart,generate}=modules;
const input=readFileSync('fixtures/sample-chart-hierarchy.pptx');
const parse=bytes=>core.parse(bytes,{keepPackage:true,edit:true,lazy:false});
const p=await parse(input),doc=edit.createDoc(p),editor=new edit.Editor(doc),api=chart.createChartDataEditor(editor);
const texts=elements=>elements.flatMap(e=>e.kind==='group'?texts(e.children):e.kind==='shape'&&e.text?[e.text.paragraphs.map(p=>p.runs.map(r=>r.text).join('')).join('\n')]:[]);
assert.equal(texts(p.slides[0].elements).some(text=>text==='3'||text==='4'),false,'空类别不应被渲染成序号标签');
const id=chart.listEditableCharts(doc)[0].id;
let data=chart.queryChartData(doc,id);
assert.equal(data.binding.mode,'workbook','多级类别的矩形范围可以原子同步工作簿');
assert.deepEqual(data.categories.map(c=>c.levels),[['North','A'],[null,'A'],['South',''],['',null],[null,'0']]);
api.setCategoryPath(id,data.categories[0].id,['West','A']);
const saved=await editor.save(),parts=unzipSync(saved);
const book=unzipSync(parts['ppt/embeddings/hierarchy1.xlsx']);
const sheet=new JSDOM(strFromU8(book['xl/worksheets/sheet1.xml']),{contentType:'text/xml'}).window.document;
assert.equal(sheet.querySelector('[r="A2"]').textContent,'West');
assert.equal(sheet.querySelector('[r="A3"]').textContent,'West','重复工作簿父标签跟随组首改名');
assert.equal(sheet.querySelector('[r="B6"]').textContent,'0');
assert.equal(sheet.querySelector('[r="B6"]').hasAttribute('t'),false,'数值零保持数字类型');
const result=await parse(saved);
const reopenedDoc=edit.createDoc(result);
const after=chart.queryChartData(reopenedDoc,chart.listEditableCharts(reopenedDoc)[0].id);
assert.deepEqual(after.categories[0].levels,['West','A']);
result.dispose();editor.dispose();p.dispose();
const removed=await parse(input),removedEditor=new edit.Editor(edit.createDoc(removed));
const removedId=chart.listEditableCharts(removedEditor.doc)[0].id,removedApi=chart.createChartDataEditor(removedEditor);
const initial=chart.queryChartData(removedEditor.doc,removedId);
removedApi.removeCategory(removedId,initial.categories[0].id);
const remaining=chart.queryChartData(removedEditor.doc,removedId);
assert.equal(remaining.categories[0].id,initial.categories[1].id);
assert.deepEqual(remaining.categories[0].levels,['North','A'],'删除组首仍保留剩余类别的父组');
removedApi.setCategoryLevel(removedId,remaining.categories[0].id,0,null);
assert.deepEqual(chart.queryChartData(removedEditor.doc,removedId).categories[0].levels,[null,'A'],'用户明确清除提升后的父组必须生效');
removedEditor.undo();
assert.deepEqual(chart.queryChartData(removedEditor.doc,removedId).categories[0].levels,['North','A'],'清除撤销恢复自动跨度');
removedEditor.undo();
assert.deepEqual(chart.queryChartData(removedEditor.doc,removedId).categories,initial.categories,'连续撤销不留下额外组首');
removedEditor.redo();removedEditor.redo();
assert.deepEqual(chart.queryChartData(removedEditor.doc,removedId).categories[0].levels,[null,'A']);
removedEditor.undo();
const addedId=removedApi.addCategory(removedId,['East','C']);
assert.deepEqual(chart.queryChartData(removedEditor.doc,removedId).categories.at(-1).levels,['East','C']);
removedApi.addSeries(removedId,'Series 3');
const expandedBytes=await removedEditor.save();writeFileSync(join(out,'edited.pptx'),expandedBytes);
const expanded=await parse(expandedBytes),expandedDoc=edit.createDoc(expanded);
const expandedData=chart.queryChartData(expandedDoc,chart.listEditableCharts(expandedDoc)[0].id);
assert.equal(expandedData.binding.mode,'workbook');
assert.equal(expandedData.categories.at(-1).id,addedId);
assert.deepEqual(expandedData.categories.at(-1).levels,['East','C']);
assert.equal(expandedData.series.length,3);
expanded.dispose();removedEditor.dispose();removed.dispose();
const mismatchParts=unzipSync(input),mismatchBook=unzipSync(mismatchParts['ppt/embeddings/hierarchy1.xlsx']);
mismatchBook['xl/worksheets/sheet1.xml']=strToU8(strFromU8(mismatchBook['xl/worksheets/sheet1.xml']).replace('<t>North</t>','<t>WRONG</t>'));
mismatchParts['ppt/embeddings/hierarchy1.xlsx']=zipSync(mismatchBook);
const mismatch=await parse(zipSync(mismatchParts)),mismatchDoc=edit.createDoc(mismatch);
assert.equal(chart.listEditableCharts(mismatchDoc)[0].binding.mode,'readonly','缓存和工作簿不同源时不猜测哪份数据正确');
mismatch.dispose();
const emptied=await parse(input),emptyEditor=new edit.Editor(edit.createDoc(emptied));
const emptyId=chart.listEditableCharts(emptyEditor.doc)[0].id,emptyApi=chart.createChartDataEditor(emptyEditor);
for(const category of chart.queryChartData(emptyEditor.doc,emptyId).categories) emptyApi.removeCategory(emptyId,category.id);
emptyApi.addCategory(emptyId,'new');
assert.deepEqual(chart.queryChartData(emptyEditor.doc,emptyId).categories[0].levels,[null,'new'],'新增类别不能复活已删除的父组');
const firstAdded=chart.queryChartData(emptyEditor.doc,emptyId).categories[0].id;
emptyApi.setCategoryLevel(emptyId,firstAdded,0,'Added');
emptyApi.setCategoryLevel(emptyId,firstAdded,1,'Leaf');
assert.deepEqual(chart.queryChartData(emptyEditor.doc,emptyId).categories[0].levels,['Added','Leaf'],'连续改单级使用最新路径');
emptyApi.addCategory(emptyId,'Successor');
emptyApi.removeCategory(emptyId,firstAdded);
assert.deepEqual(chart.queryChartData(emptyEditor.doc,emptyId).categories[0].levels,['Added','Successor'],'新增组首删除后仍保留其后继类别的父组');
emptyEditor.dispose();emptied.dispose();
const replaced=await parse(input),replaceEditor=new edit.Editor(edit.createDoc(replaced));
const replaceId=chart.listEditableCharts(replaceEditor.doc)[0].id,replaceApi=chart.createChartDataEditor(replaceEditor);
replaceApi.removeCategory(replaceId,chart.queryChartData(replaceEditor.doc,replaceId).categories.at(-1).id);
replaceApi.addCategory(replaceId,['','0']);
const replacedParts=unzipSync(await replaceEditor.save()),replacedBook=unzipSync(replacedParts['ppt/embeddings/hierarchy1.xlsx']);
const replacedSheet=new JSDOM(strFromU8(replacedBook['xl/worksheets/sheet1.xml']),{contentType:'text/xml'}).window.document;
assert.equal(replacedSheet.querySelector('[r="B6"]').getAttribute('t'),'inlineStr','新文本零不继承被删单元格的数字类型');
replaceEditor.dispose();replaced.dispose();
const joined=await parse(input),joinEditor=new edit.Editor(edit.createDoc(joined));
const joinId=chart.listEditableCharts(joinEditor.doc)[0].id,joinApi=chart.createChartDataEditor(joinEditor),joinInitial=chart.queryChartData(joinEditor.doc,joinId);
joinApi.setCategoryLevel(joinId,joinInitial.categories[3].id,0,null);
joinApi.removeCategory(joinId,joinInitial.categories[2].id);
assert.deepEqual(chart.queryChartData(joinEditor.doc,joinId).categories[2].levels,['South',null],'清空后继承的父组在其前驱被删时仍保留');
joinEditor.dispose();joined.dispose();
const reset=await parse(input),resetEditor=new edit.Editor(edit.createDoc(reset));
const resetId=chart.listEditableCharts(resetEditor.doc)[1].id,resetApi=chart.createChartDataEditor(resetEditor);
const resetPoint=chart.queryChartData(resetEditor.doc,resetId).categories[2].id;
resetApi.setCategoryPath(resetId,resetPoint,['New root',null,'']);
assert.deepEqual(chart.queryChartData(resetEditor.doc,resetId).categories[2].levels,['New root',null,''],'更换根组并清空下级时不能跨父组继承');
for(const category of chart.queryChartData(resetEditor.doc,resetId).categories)if(category.id!==resetPoint)resetApi.removeCategory(resetId,category.id);
assert.deepEqual(chart.queryChartData(resetEditor.doc,resetId).categories[0].levels,['New root',null,''],'删除其他类别不能复活旧根下的子组');
resetEditor.dispose();reset.dispose();
await testHierarchyRoundTrips({...modules,input,out,assert});
await testHierarchyCollaboration({...modules,input,assert});
await testHierarchyBoundaries({...modules,input,assert});
record();
